#!/usr/bin/env python3
"""Regenerate the filecheck directives of filetests from the compiler's actual output.

    tools/update_filecheck.py tests/filetests/x86_64            # a directory, recursively
    tools/update_filecheck.py 'tests/filetests/wasm/*.sir'      # a glob
    tools/update_filecheck.py tests/filetests/print/add.sir     # a single file

Only files carrying the autogenerated NOTE line are rewritten, so hand-written partial checks
are never clobbered. Pass --force to take over a file: its existing directives are replaced by
the full output and the NOTE line is added.
"""

import argparse
import glob
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILETESTS = ROOT / "tests" / "filetests"
NOTE = "; NOTE: Assertions have been autogenerated by tools/update_filecheck.py"
DIRECTIVE = re.compile(r"^;\s*(check|sameln|nextln|unordered|not|regex):")
MAX_ROUNDS = 5


def collect(patterns):
    files = []
    for pattern in patterns:
        matches = glob.glob(pattern, recursive=True) if glob.has_magic(pattern) else [pattern]
        if not matches:
            sys.exit(f"error: no match for `{pattern}`")
        for match in matches:
            path = Path(match).resolve()
            if path.is_dir():
                files.extend(sorted(path.rglob("*.sir")))
            elif path.is_file():
                files.append(path)
            else:
                sys.exit(f"error: `{match}` does not exist")
    unique = sorted(set(files))
    for path in unique:
        if FILETESTS not in path.parents:
            sys.exit(f"error: {path} is not under {FILETESTS}")
    return unique


def render_checks(output):
    checks = []
    after_blank = True
    for raw in output.splitlines():
        line = raw.rstrip()
        if not line.strip():
            after_blank = True
            continue
        if "{{" in line or "[[" in line:
            raise ValueError(f"cannot express `{line.strip()}` as a literal check")
        kind = "check" if after_blank else "nextln"
        checks.append(f"; {kind}: {line.replace('$', '$$')}")
        after_blank = False
    return checks


def rewrite(source, output):
    body = [l for l in source.split("\n") if l != NOTE and not DIRECTIVE.match(l)]
    start = next(
        (i for i, l in enumerate(body) if l.strip() and not l.startswith(";")), len(body)
    )
    return "\n".join(body[:start] + [NOTE] + render_checks(output) + body[start:])


def dump_outputs():
    with tempfile.TemporaryDirectory() as tmp:
        env = dict(os.environ, FILECHECK_DUMP_DIR=tmp)
        run = subprocess.run(
            ["cargo", "test", "--release", "--test", "filetests", "--quiet"],
            cwd=ROOT,
            env=env,
            capture_output=True,
            text=True,
        )
        if "could not compile" in run.stderr:
            sys.exit(run.stderr)
        return {
            path.relative_to(tmp).with_suffix(".sir"): path.read_text()
            for path in Path(tmp).rglob("*.out")
        }


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("paths", nargs="+", help="files, directories or globs under tests/filetests")
    parser.add_argument("--force", action="store_true", help="also take over files without the NOTE line")
    args = parser.parse_args()

    targets = []
    for path in collect(args.paths):
        if not args.force and NOTE not in path.read_text():
            print(f"skipped (not autogenerated, use --force): {path.relative_to(ROOT)}")
        else:
            targets.append(path)

    updated = set()
    failed = set()
    for _ in range(MAX_ROUNDS):
        outputs = dump_outputs()
        changed = False
        for path in targets:
            output = outputs.get(path.relative_to(FILETESTS))
            if output is None:
                failed.add(path)
                continue
            old = path.read_text()
            new = rewrite(old, output)
            if new != old:
                path.write_text(new)
                updated.add(path)
                changed = True
        targets = [p for p in targets if p not in failed]
        if not changed:
            break
    else:
        sys.exit("error: output did not stabilise (does it depend on the check lines?)")

    for path in sorted(updated):
        print(f"updated: {path.relative_to(ROOT)}")
    for path in sorted(failed):
        print(f"no output (stage failed, see `cargo test --test filetests`): {path.relative_to(ROOT)}")
    print(f"{len(updated)} updated, {len(targets) - len(updated)} unchanged, {len(failed)} failed")


if __name__ == "__main__":
    main()
